def compass(cx, cy, r):
    """An engraver's compass rose, as SVG elements for an existing <svg>."""
    out = [
        f'<circle cx="{cx}" cy="{cy}" r="{r}" fill="none" stroke="#1f1a14" stroke-width="1.2"/>',
        f'<circle cx="{cx}" cy="{cy}" r="{r - 5}" fill="none" stroke="#1f1a14" stroke-width=".6"/>',
    ]
    for k in range(8):
        a = math.radians(k * 45)
        length = r - 8 if k % 2 == 0 else (r - 8) * 0.55
        tip = (cx + length * math.sin(a), cy - length * math.cos(a))
        w = 6 if k % 2 == 0 else 4
        left = (cx + w * math.sin(a - math.pi / 2), cy - w * math.cos(a - math.pi / 2))
        right = (cx + w * math.sin(a + math.pi / 2), cy - w * math.cos(a + math.pi / 2))
        out.append(
            f'<path d="M{tip[0]:.1f} {tip[1]:.1f} L{left[0]:.1f} {left[1]:.1f} L{cx} {cy}Z" fill="#1f1a14"/>'
            f'<path d="M{tip[0]:.1f} {tip[1]:.1f} L{right[0]:.1f} {right[1]:.1f} L{cx} {cy}Z" fill="#f1e7d0" '
            f'stroke="#1f1a14" stroke-width=".7"/>'
        )
    out.append(
        f'<text x="{cx}" y="{cy - r - 7}" text-anchor="middle" font-family="IM Fell English SC, serif" '
        f'font-size="15" fill="#1f1a14">N</text>'
    )
    return "".join(out)


