def page(name, w, h, body, scale=2, quality="84"):
    """Writes one picture's page. quality is the JPEG quality, or "png" to keep the transparent ground."""
    doc = (
        f'<!doctype html><html lang="en"><head><meta charset="utf-8"><title>{name}</title>{FONTS}'
        f"<style>{CSS}</style></head>"
        f'<body style="width:{w}px;height:{h}px;overflow:hidden">{body}</body></html>'
    )
    (BUILD / f"{name}.html").write_text(doc, encoding="utf-8")
    PAGES.append((name, w, h, scale, quality))


